"""Write the portfolio's data/modelLabResults.ts from evals/results/*.json. Usage: python scripts/site_results.py <out.ts>"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent / "evals" / "results"
summ = json.loads((root / "summary.json").read_text())
recs = json.loads((root / "datasets.json").read_text())["records"]
live_p = root / "live.json"
live = json.loads(live_p.read_text()) if live_p.exists() else None
s = summ["summary"]

rows = []
for rec in recs:
    runs = [r for r in rec["runs"] if "claimed" in r]
    if not runs:
        continue
    n = len(runs)
    rows.append({
        "name": rec["dataset"], "task": rec["task"], "rows": rec["rows"], "runs": n,
        "claimed": sum(r["claimed"] for r in runs) / n, "outer": sum(r["outer"] for r in runs) / n,
        "baseline": sum(r["baseline_outer"] for r in runs) / n, "regretMax": max(r["regret"] for r in runs),
        "leak": [sum(1 for r in runs if r.get("leak_caught")), sum(1 for r in runs if r.get("leak_caught") is not None)],
        "shuffled": [sum(r["shuffled"]["false_alarms"] for r in runs), sum(r["shuffled"]["runs"] for r in runs)],
        "missedUseful": sum(1 for r in runs if not r["says_beats_baseline"] and r["really_beats_baseline"]),
        "primary": "r2" if rec["task"] == "regression" else "classification",
    })
skipped = [f'{x["dataset"]} (could not be downloaded)' for x in summ["skipped"]]
for rec in recs:
    if not any("claimed" in r for r in rec["runs"]):
        err = (rec["runs"][0].get("error") or "") if rec["runs"] else ""
        why = "more than the 40-column limit" if "Too many columns" in err else "could not be run"
        skipped.append(f'{rec["dataset"]} ({rec["columns"]} columns, {why})' if "Too many columns" in err else f'{rec["dataset"]} ({why})')
out = {
    "datasets": s["datasets"], "runs": s["runs"], "seeds": len(summ["seeds"]),
    "regretMedian": s["regret_median"], "regretWithin2": s["regret_within_2pts"],
    "gapMedian": s["gap_median"], "coverage": s["coverage"],
    "falseAlarms": s["false_alarms"], "shuffledRuns": s["shuffled_runs"],
    "leakCaught": s["leak_caught"], "leakRuns": s["leak_runs"],
    "falseLeakFlags": s["false_leak_flags"], "cleanRuns": s["clean_runs"],
    "usefulAndIs": s["says_useful_and_is"], "usefulButIsnt": s["says_useful_but_isnt"],
    "missedUseful": sum(r["missedUseful"] for r in rows),
    "skipped": skipped,
    "perDataset": rows,
    "live": None if not live else {
        "when": live["when"],
        "runs": [{"sample": r["sample"], "seconds": r["seconds"], "rows": r.get("rows")} for r in live["runs"] if r.get("status") == "done"],
        "failed": [r["sample"] for r in live["runs"] if r.get("status") != "done"],
    },
}
text = ("// Generated by scripts/site_results.py in the model-lab repository from the committed benchmark results. Do not edit by hand.\n"
        "export type LabBench = {\n  datasets: number; runs: number; seeds: number;\n  regretMedian: number; regretWithin2: number; gapMedian: number; coverage: number;\n"
        "  falseAlarms: number; shuffledRuns: number; leakCaught: number; leakRuns: number; falseLeakFlags: number; cleanRuns: number;\n"
        "  usefulAndIs: number; usefulButIsnt: number; missedUseful: number; skipped: string[];\n"
        "  perDataset: { name: string; task: string; rows: number; runs: number; claimed: number; outer: number; baseline: number; regretMax: number; leak: number[]; shuffled: number[]; missedUseful: number; primary: string }[];\n"
        "  live: { when: string; runs: { sample: string; seconds: number; rows: number | null }[]; failed: string[] } | null;\n};\n"
        f"export const MODEL_LAB_BENCH: LabBench | null = {json.dumps(out, indent=2)};\n")
pathlib.Path(sys.argv[1]).write_text(text)
print("wrote", sys.argv[1], s["datasets"], "datasets,", s["runs"], "runs")
